// Subsets Phosphor into src/ui/icons.tsx with only the icons and weights LTOC uses.
// @phosphor-icons/react ships all six weights per icon (~2.5 kB each); this keeps one or two.
// Run: npm run icons   (after adding a name to ICONS below)
import { readFileSync, writeFileSync } from 'node:fs'

const ICONS = {
  // name: extra weights beyond "bold"
  Ambulance: [], ArrowCounterClockwise: [], ArrowsSplit: [], BellRinging: [], Broadcast: [], Buildings: [], CaretRight: [], Car: [],
  ChartBar: [], ChartLine: [], Check: [], ClipboardText: [], FireTruck: [], Flag: [], FlowArrow: [], Lifebuoy: [], Lightning: ['fill'],
  Link: [], MagnifyingGlass: [], MapTrifold: [], Megaphone: [], Moon: [], NotePencil: [], Pause: [], Phone: [], Play: [], Siren: [],
  Sparkle: ['fill'], SquaresFour: [], Sun: [], Truck: [], User: [], UsersThree: [], VideoCamera: [], Warning: [], WarningCircle: ['fill'],
  WifiHigh: [], X: [],
}
const kebab = n => n.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase()
const inner = (name, weight) => {
  const file = new URL(`../node_modules/@phosphor-icons/core/assets/${weight}/${kebab(name)}${weight === 'regular' ? '' : `-${weight}`}.svg`, import.meta.url)
  return readFileSync(file, 'utf8').replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '')
}
let out = `// GENERATED by scripts/build-icons.mjs from @phosphor-icons/core. Do not edit; run \`npm run icons\`.
// Phosphor icons (MIT). Only the "bold" weight, plus "fill" where marked.
import type { SVGProps } from 'react'

export type IconProps = Omit<SVGProps<SVGSVGElement>, 'dangerouslySetInnerHTML'> & { size?: number; weight?: 'bold' | 'fill' }
type Paths = { bold: string; fill?: string }
const make = (p: Paths) => ({ size = 16, weight = 'bold', ...rest }: IconProps) =>
  <svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256" width={size} height={size} fill="currentColor" aria-hidden {...rest} dangerouslySetInnerHTML={{ __html: weight === 'fill' && p.fill ? p.fill : p.bold }} />

`
for (const [name, extra] of Object.entries(ICONS)) {
  const paths = { bold: inner(name, 'bold'), ...Object.fromEntries(extra.map(w => [w, inner(name, w)])) }
  out += `export const ${name} = make(${JSON.stringify(paths)})\n`
}
writeFileSync(new URL('../src/ui/icons.tsx', import.meta.url), out)
console.log(`wrote ${Object.keys(ICONS).length} icons`)
